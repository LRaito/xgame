function imageSet(id, consoles = 4, media = 3) {
    return {
        consoles: Array.from({ length: consoles }, (_, index) => `${id}-console-${index + 1}`),
        media: Array.from({ length: media }, (_, index) => `${id}-media-${index + 1}`),
    };
}

